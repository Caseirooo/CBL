    public RecipeDetailFrame(RecipeMatchResult recipeMatchResult, Pantry pantry) {
        initComponents();
        setSize(WindowSize.WIDTH, WindowSize.HEIGHT);
        setLocationRelativeTo(null);
        this.recipeMatchResult = recipeMatchResult;
        this.pantry = pantry;
        recipe = recipeMatchResult.getRecipe();
        nameLabel.setText(recipe.getName());
        infoLabel.setText(recipe.difficultyToWord() + " · "
                + recipe.getPrepTime() + " min" + " · "
                + recipeMatchResult.getPercentage() + "%");

        String ingredientsText = "";
        for (Ingredient ingredient : recipe.getIngredients()) {
            ingredientsText += ingredient.getName() + ": "
                    + ingredient.getQuantity() + "\n";
        }
        ingredientsTextArea.setText(ingredientsText);

        String missingIngredientsText = "";
        for (Ingredient missingIngredient : recipeMatchResult.getMissingIngredients()) {
            missingIngredientsText += missingIngredient.getName() + ": " + missingIngredient.getQuantity() + "\n";
        }

        if (missingIngredientsText.isEmpty()) {
            missingIngredientsText = "You have all of the ingredients!";
        }
        missingIngredientsTextArea.setText(missingIngredientsText);

        String instructionsText = "";
        for (int i = 0; i < recipe.getInstructions().size(); i++) {
            instructionsText += (i + 1) + ". " + recipe.getInstructions().get(i) + "\n\n";
        }
        instructionsTextArea.setText(instructionsText);
    }

